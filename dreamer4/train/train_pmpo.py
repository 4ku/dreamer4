class DemoStarts:
    """The contexts dreams start from, read from the recorded episodes.

    Paper Section 3.3: "Imagined rollouts start from contexts of the dataset that was used during
    the earlier training phases. Unlike previous generations of Dreamer, we start only one rollout
    from each context." A context here is a whole window ending at a recorded frame, built by the
    convention in :mod:`dreamer4.models.world_model` -- so a dream begins with the same kind of
    history the policy was trained on and will meet at evaluation. The window carries
    ``tokenizer.history - 1`` extra leading frames, so the tokenizer encodes its first slot from the
    frames that really preceded it. Contexts are drawn uniformly over all recorded frames.
    """

    def __init__(self, dataset, *, window, history, rng=None):
        self.window = int(window)
        self.span = int(window) + int(history) - 1
        self.n_actions = int(dataset.action_dim)
        frames, proprio, into, task, local = [], [], [], [], []
        offset = 0
        for i in range(len(dataset)):
            n = dataset.episode_frames(i)
            clip = dataset.clip(i, 0, n)
            # The last frame of an episode that ENDED is not a start: there is nothing left to do
            # from it.
            keep = n - 1 if "terminals" in clip and bool(clip["terminals"][-1]) else n
            if keep <= 0:
                continue
            frames.append(clip["video"][:n])
            proprio.append(clip["proprio"][:n].astype(np.float32))
            led = np.full(n, -1, np.int64)                  # action that led INTO each frame
            led[1:] = clip["actions"][:n - 1].argmax(-1)
            into.append(led)
            # The paper's task indicator, recorded per episode by a multi-task collector.
            task.append(np.full(n, int(dataset.episode_meta(i).get("task", 0)), np.int64))
            local.append((offset, keep))
            offset += n
        self.frames = np.concatenate(frames)
        self.proprio = np.concatenate(proprio)
        self.into = np.concatenate(into)
        self.task = np.concatenate(task)
        # Global index of every legal start, and the episode offset it belongs to, so a window can
        # be clamped at its own episode's first frame rather than the array's.
        self.index = np.concatenate([np.arange(o, o + k) for o, k in local])
        self.base = np.concatenate([np.full(k, o) for o, k in local])
        self.rng = rng or np.random.default_rng(0)

    def sample(self, n):
        """``n`` contexts. Returns the encode window, its proprio, its aligned actions and task."""
        pick = self.rng.choice(len(self.index), n)
        end = self.index[pick]
        base = self.base[pick]
        slots = window_frames(end - base, self.span) + base.reshape(-1, 1)
        win = slots[:, -self.window:]
        led = self.into[win]
        aligned = np.zeros((n, self.window, self.n_actions + 1), np.float32)
        fresh = np.ones_like(win, bool)
        fresh[:, 1:] = win[:, 1:] != win[:, :-1]
        fresh[:, 0] = False                            # slot 0 always carries the start flag
        fresh &= led >= 0
        rows, cols = np.nonzero(fresh)
        aligned[rows, cols, led[rows, cols]] = 1.0
        aligned[~fresh, -1] = 1.0
        return {"encode": self.frames[slots], "proprio": self.proprio[win],
                "actions": aligned, "task": self.task[end]}


class Tape:
    """The per-episode buffers a dream fills, and the masks the update reads them through.

    ``continues`` and ``alive`` are the only two the losses ever index by: ``alive[:, t]`` marks a
    state the policy really occupied, ``continues[:, t]`` is the ``c_t`` of Eq. 10. Both are filled
    from the per-row termination step in one place.
    """

    def __init__(self, B, horizon, device):
        self.B, self.H, self.device = B, horizon, device
        self.actions = torch.zeros(B, horizon, dtype=torch.long, device=device)
        self.rewards = torch.zeros(B, horizon, device=device)
        self.done = np.zeros(B, bool)
        self.term_at = np.full(B, -1)
        self.n_states = np.full(B, horizon + 1)

    def terminate(self, t, is_terminal):
        """Mark the rows whose frame ``t`` the reward head calls terminal."""
        newly = (~self.done) & np.asarray(is_terminal, bool)
        self.term_at[newly] = t
        self.n_states[newly] = t + 1
        self.done |= newly
        return newly

    def finish(self, extra):
        cont = torch.ones(self.B, self.H + 1, device=self.device)
        alive = torch.zeros(self.B, self.H + 1, device=self.device)
        for i in range(self.B):
            if self.term_at[i] >= 0:
                cont[i, self.term_at[i]:] = 0.0
                alive[i, :self.term_at[i] + 1] = 1.0
            else:
                alive[i, :self.n_states[i]] = 1.0
                cont[i, self.n_states[i]:] = 0.0
        term = self.term_at >= 0
        return {"actions": self.actions, "rewards": self.rewards,
                "continues": cont, "alive": alive,
                "terminated": torch.as_tensor(term, device=self.device),
                "success": float(term.mean()), **extra}


class Imagination:
    """The agent heads on top of the frozen world model: rollout, scoring, losses, checkpoints.

    The rollout runs the world model without gradients and keeps the agent embeddings ``h_t`` it
    produced; the update re-runs ONLY the heads over that buffer. Because the transformer is frozen
    this is exact.
    """

    def __init__(self, world, heads, ckpt, cfg, device):
        self.world, self.heads, self.cfg, self.device = world, heads, cfg, device
        self.clip_T = int(ckpt["clip_T"])
        self.d_in = heads.d_in
        self.bins = heads.reward.twohot.bin_values.detach().to(device)
        self.term_bin = terminal_bins(heads.reward, world.continues_from_reward, device)
        self.prior = copy.deepcopy(heads.policy).eval()
        for p in self.prior.parameters():
            p.requires_grad_(False)
        # Only the policy and the value head move (Section 3.3). The agent-token encoder is an
        # INPUT to the frozen transformer, so its gradient would have to travel back through a
        # forward this phase never repeats -- it is frozen with the rest of the world model.
        for module in (heads.tokens, heads.reward):
            for p in module.parameters():
                p.requires_grad_(False)
        self.policy_params = list(heads.policy.parameters())
        self.value_params = list(heads.value.parameters())
        self.ckpt = ckpt

    def decode_reward(self, probs):
        """The scalar reward a dream pays, from the reward head's distribution over bins.

        ``mean`` is the expectation over all bins. ``mode`` is the two-hot mean restricted to the
        most likely bin and its two neighbours: a categorical head always leaks a little mass onto
        far bins, and where one rare reward dwarfs the per-step one that leak IS the signal's size
        -- on the gridworld 1 % of mass on the +1 bin pays +0.01, exactly the step cost, and it
        concentrates near the goal (measured in dreams: a wrong move two cells from the goal had a
        HIGHER mean return than the optimal one). A recorded reward is two-hot encoded onto two
        adjacent bins, so the local mean decodes it exactly and ignores the leak.
        """
        if self.cfg.reward_decode == "mean":
            return (probs * self.bins).sum(-1)
        top = probs.argmax(-1, keepdim=True)
        idx = (top + torch.arange(-1, 2, device=probs.device)).clamp(0, probs.shape[-1] - 1)
        local = probs.gather(-1, idx)
        # a clamped index repeats an edge bin; count it once
        local = local * torch.cat([idx[..., :1] != idx[..., 1:2], torch.ones_like(idx[..., :1], dtype=torch.bool),
                                   idx[..., 2:] != idx[..., 1:2]], -1)
        return (local * self.bins[idx]).sum(-1) / local.sum(-1).clamp_min(1e-8)

    def eval_policy(self):
        return AgentPolicy(self.world.dyn, self.heads, window=self.clip_T,
                           tau_ctx=self.world.tau_ctx, k_max=self.world.k_max)

    @torch.no_grad()
    def rollout(self, starts_batch, *, horizon, K, term_prob):
        world, heads, dev = self.world, self.heads, self.device
        B = len(starts_batch["encode"])
        D = world.action_vec_dim
        hist = world.tok.history

        # The recorded context, encoded exactly as phase 2 encoded it.
        z = world.tok.encode_frames(starts_batch["encode"])[:, hist - 1:].float().to(dev)
        prop = torch.as_tensor(starts_batch["proprio"], device=dev)
        act_hist = torch.as_tensor(starts_batch["actions"], device=dev)
        task = torch.as_tensor(starts_batch["task"], device=dev)
        # One KV cache holding ``clip_T - 1`` PAST frames: the frame being committed (or denoised)
        # is the window's last slot, so the policy reads ``clip_T`` slots -- the clips phase 2
        # trained on and the window the evaluator plays with -- and the dynamics denoises against
        # as many past frames as ITS training windows had. A longer cache is not a richer context,
        # it is a broken simulator: the flow head has never seen it. Measured on the empty maze
        # (dynamics trained on 4-frame windows, recorded actions replayed through this loop): up
        # to 5 past frames the dreamed player is in the wrong cell on 0.2 % of the steps, with 7
        # or 11 on 93-94 % -- and that is what `main` refuses below.
        cache = world.dyn.transformer.make_kv_cache()
        cache.max_T = max(1, self.clip_T - 1)

        tape = Tape(B, horizon, dev)
        H = torch.zeros(B, horizon + 1, self.d_in, device=dev)
        t = 0
        for t in range(horizon + 1):
            new = z.shape[1] if t == 0 else 1
            h = dream_context(world, heads, z_hist=z[:, -new:], prop_hist=prop[:, -new:],
                              act_hist=act_hist[:, -new:], tau_ctx=world.tau_ctx,
                              task_ids=task, cache=cache, commit=True)
            H[:, t] = h.float()
            if t > 0:
                # The reward head reads the reward that ARRIVED with this frame, i.e. the reward of
                # the t-1 -> t transition, and the terminal rule on the same distribution says
                # whether this frame ends the episode.
                probs = heads.reward.at(h, 0).float().softmax(-1)
                tape.rewards[:, t - 1] = (self.decode_reward(probs)
                                          * torch.as_tensor(~tape.done, device=dev))
                p_term = (probs * self.term_bin).sum(-1)
                tape.terminate(t, (p_term > term_prob).cpu().numpy())
                if tape.done.all():
                    break
            if t == horizon:
                break
            logits = heads.policy.at(h, 0).float()
            a = torch.distributions.Categorical(logits=logits).sample()
            tape.actions[:, t] = a
            av = torch.zeros(B, 1, D + 1, device=dev)
            av[torch.arange(B), 0, a.clamp(max=D - 1)] = 1.0
            act_hist = torch.cat([act_hist, av], 1)
            z_new, prop_new = dream_step(world, z_hist=z, prop_hist=prop,
                                         act_hist=act_hist[:, -(z.shape[1] + 1):], K=K, cache=cache)
            z = torch.cat([z, z_new[:, None]], 1)
            prop = torch.cat([prop, prop_new[:, None]], 1)
        H[:, t + 1:] = H[:, t:t + 1]                  # freeze the tail of finished episodes
        return tape.finish({"H": H})

    def score(self, roll):
        """Policy logits, the value distribution and its decoded mean -- all with gradients."""
        h = roll["H"]
        logits = self.heads.policy.at(h, 0).float()
        vlogits = self.heads.value.at(h, 0).float()
        return logits, vlogits, self.heads.value.mean(vlogits)

    def value_loss(self, vlogits, targets, alive):
        """Paper Eq. 10: ``- ln p(R^lambda_t | s_t)`` against the two-hot encoding of the return."""
        nll = -self.heads.value.twohot.log_prob(vlogits, targets.detach())
        return (nll * alive).sum() / alive.sum().clamp_min(1.0)

    def prior_logits(self, roll, horizon):
        return self.prior.at(roll["H"][:, :horizon], 0).float()

    def save(self, path, extra):
        torch.save({**{k: v for k, v in self.ckpt.items()
                       if k in ("agent_cfg", "dyn", "n_agent", "clip_T", "dyn_source")},
                    "agent": self.heads.state_dict(), "train_cfg": vars(self.cfg), **extra}, path)


