def load_agent(cfg, dev):
    """Open the phase-2 (or phase-3) checkpoint and rebuild the world model and heads from it."""
    ckpt = torch.load(cfg.init_from, map_location="cpu", weights_only=False)
    world = WorldModel(cfg.dyn, device=cfg.device, n_agent=int(ckpt["n_agent"]))
    # The transformer phase 2 finetuned IS the world model from here on.
    world.load_dynamics_weights(ckpt["dyn"])
    world.dyn.eval()
    heads = build_agent_heads(ckpt["agent_cfg"]).to(dev)
    heads.load_state_dict(ckpt["agent"])
    return world, Imagination(world, heads, ckpt, cfg, dev)


def main():
    cfg = parse_args()
    torch.manual_seed(cfg.seed)
    np.random.seed(cfg.seed)
    torch.set_float32_matmul_precision("high")             # tf32 matmuls
    dev = torch.device(cfg.device)
    out = Path(cfg.out)
    (out / "checkpoints").mkdir(parents=True, exist_ok=True)

    world, agent = load_agent(cfg, dev)
    if agent.clip_T > world.window:
        raise ValueError(
            f"this phase-2 checkpoint reads a {agent.clip_T}-slot context, but the dynamics model "
            f"was trained on {world.window}-frame windows: dreamed with {agent.clip_T - 1} past "
            f"frames it stops following the actions (the player lands in the wrong cell on >90 % "
            f"of the steps), so the policy would be optimised inside a broken simulator. Rerun "
            f"phase 2 with --clip_T <= {world.window}, or train phase 1b with a longer "
            f"--data.seq_len.")
    if cfg.horizon <= 0:
        longest = max(world.dataset.episode_frames(i) for i in range(len(world.dataset))) - 1
        cfg.horizon = longest if longest > 0 else 40
    json.dump({**vars(cfg), "data": world.data_path}, open(out / "config.json", "w"), indent=1)
    if cfg.compile:
        world.dyn = torch.compile(world.dyn, dynamic=True)
    print(f"warm start + KL prior from {cfg.init_from}", flush=True)

    opt = torch.optim.AdamW([{"params": agent.policy_params, "lr": cfg.lr},
                             {"params": agent.value_params, "lr": cfg.value_lr}], weight_decay=0.0)
    base_lrs = [cfg.lr, cfg.value_lr]

    rng = np.random.default_rng(cfg.seed)
    starts = DemoStarts(world.dataset, window=agent.clip_T, history=world.tok.history, rng=rng)
    print(f"dream starts: {len(starts.index)} contexts of {agent.clip_T} frames from "
          f"{world.data_path} | horizon {cfg.horizon}", flush=True)
    eval_envs = [make_env(world.env_spec) for _ in range(cfg.eval_envs)] if world.env_spec else []
    if not eval_envs:
        print("no env_spec in this dataset: real-env evaluation is skipped and no best.pt is "
              "written", flush=True)
    eval_policy = agent.eval_policy()
    # A rerun into the same --out replaces everything: the metrics file is truncated and
    # TensorBoard purges from step 0, so the two never disagree about which run they describe.
    mf = open(out / "metrics.jsonl", "w", buffering=1)
    writer = SummaryWriter(str(out / "tb"), purge_step=0)
    tb_names = {"dream_success": "dream/success_rate", "value_loss": "critic/value_loss",
                "grad_norm": "train/grad_norm", "entropy": "policy/entropy",
                "kl_to_prior": "policy/kl_to_bc_prior", "pos_frac": "pmpo/positive_adv_frac",
                "dreams": "dream/imagined_episodes", "it_s": "train/steps_per_sec_cumulative"}
    t_last = s_last = None

    B, H = cfg.batch, cfg.horizon
    # best starts BELOW every reachable success rate, so a policy that never succeeds still writes
    # best.pt and the script's resume check cannot mark the phase done with a missing artifact.
    collected, best = 0, -1.0
    last_eval, best_eval = {}, {}
    t0 = time.time()
    for step in range(cfg.steps):
        do_log = step % cfg.log_every == 0
        frac = step / max(1, cfg.steps - 1)
        for group, lr0 in zip(opt.param_groups, base_lrs):
            group["lr"] = lr0 * (1.0 - frac) + cfg.lr_final * frac

        # On-policy: one fresh batch of dreams per update.
        with torch.autocast("cuda", torch.bfloat16, enabled=bool(cfg.amp)):
            roll = agent.rollout(starts.sample(B), horizon=H, K=cfg.K, term_prob=cfg.term_prob)
        collected += 1

        alive = roll["alive"]
        with torch.autocast("cuda", torch.bfloat16, enabled=bool(cfg.amp)):
            lg, vlogits, v = agent.score(roll)
        rewards_in = torch.cat([roll["rewards"], torch.zeros_like(roll["rewards"][:, :1])], 1)
        gates_in = torch.cat([roll["continues"][:, 1:], torch.ones_like(roll["continues"][:, :1])], 1)
        targets = compute_lambda_returns(rewards_in, v.detach(), gates_in, gamma=cfg.gamma,
                                         lam=cfg.lam)
        value_loss = agent.value_loss(vlogits, targets, alive)

        # PMPO (Eq. 11): sign-of-advantage policy term plus the reverse KL to the frozen prior.
        adv = targets[:, :H] - v.detach()[:, :H]
        # States the policy really ACTED from. The frame a dream ends on is occupied (its value,
        # zero, is a legitimate critic target) but nothing is done from it: the action the rollout
        # samples there is never executed, and its advantage is just -v(terminal). Eq. 11 only uses
        # the SIGN of the advantage, so that one junk transition per finished dream would push a
        # real action up or down at full weight -- in features that sit next to those of the
        # states adjacent to the goal, which is where the damage showed (greedy success 1.000 ->
        # 0.988 on the empty maze, every failure a loop one or two cells from the goal).
        keep = (alive[:, :H] > 0) & (roll["continues"][:, :H] > 0)
        drop = cfg.adv_drop_frac
        if cfg.adv_drop_final >= 0:
            drop += (cfg.adv_drop_final - drop) * min(1.0, step / max(1, cfg.adv_drop_steps))
        coeff, pinfo = pmpo_coeffs(adv[keep], alpha=cfg.alpha, drop_frac=drop)
        dist = torch.distributions.Categorical(logits=lg[:, :H])
        lp = dist.log_prob(roll["actions"])[keep]
        with torch.no_grad():
            plg = agent.prior_logits(roll, H)
        kl = torch.distributions.kl_divergence(dist, torch.distributions.Categorical(logits=plg))[keep]
        loss = cfg.value_weight * value_loss + (coeff * lp).sum() + cfg.beta * kl.mean()

        opt.zero_grad(set_to_none=True)
        loss.backward()
        gn = torch.nn.utils.clip_grad_norm_(agent.policy_params + agent.value_params, cfg.grad_clip)
        opt.step()

        if do_log:
            pinfo["entropy"] = float(dist.entropy()[keep].mean().detach())
            pinfo["kl_to_prior"] = float(kl.mean().detach())
            rec = {"step": step, "dreams": collected * B, "wall_s": round(time.time() - t0, 1),
                   "dream_success": roll["success"], "value_loss": value_loss.item(),
                   "grad_norm": float(gn), "it_s": (step + 1) / max(time.time() - t0, 1e-9),
                   **{k: float(x) for k, x in pinfo.items()}}
            mf.write(json.dumps(rec) + "\n")
            for k, x in rec.items():
                if k not in ("step", "wall_s"):
                    writer.add_scalar(tb_names.get(k, f"pmpo/{k}"), float(x), step)
            # it_s above is (step+1)/elapsed -- cumulative, so it cannot show a slowdown
            now = time.time()
            if t_last is not None and now > t_last:
                writer.add_scalar("train/steps_per_sec_inst", (step - s_last) / (now - t_last), step)
            t_last, s_last = now, step
            print(f"[{time.strftime('%H:%M:%S')}] step {step}/{cfg.steps} "
                  f"dreamSR {roll['success']:.2f} vloss {rec['value_loss']:.4f} "
                  f"H {pinfo['entropy']:.2f} kl {pinfo['kl_to_prior']:.3f} "
                  f"gn {float(gn):.1f} {rec['it_s']:.2f}it/s", flush=True)

        if eval_envs and ((step + 1) % cfg.eval_every == 0 or step == cfg.steps - 1):
            kw = dict(tok=world.tok, proprio_from_info=world.proprio_from_info, n=cfg.eval_n,
                      seed=cfg.eval_seed, device=dev)
            g = evaluate(eval_policy, eval_envs, greedy=True, **kw)
            s = evaluate(eval_policy, eval_envs, greedy=False, **kw)
            last_eval = {"step": step + 1, "dreams": collected * B, "greedy": g[0], "sampled": s[0],
                         "greedy_opt": g[2], "sampled_opt": s[2], "eval_n": cfg.eval_n}
            print(f"PMPO-EVAL {out.name} step {step + 1} dreams {collected * B} "
                  f"greedy SR {g[0]:.4f} opt {g[2]:.4f} | sampled SR {s[0]:.4f} opt {s[2]:.4f} "
                  f"| n={cfg.eval_n} | {(time.time() - t0) / 60:.1f} min", flush=True)
            for k, x in (("greedy_sr", g[0]), ("greedy_opt", g[2]),
                         ("sampled_sr", s[0]), ("sampled_opt", s[2])):
                writer.add_scalar(f"eval/{k}", x, step + 1)
            writer.flush()
            agent.save(out / "checkpoints" / "latest.pt", last_eval)
            # best.pt: the highest greedy success rate, ties broken by the shorter path -- the first
            # checkpoint to reach 100 % is rarely the best one (phase 2 selects the same way)
            if (g[0], -g[2]) > (best, -best_eval.get("greedy_opt", float("inf"))):
                best = g[0]
                best_eval = last_eval
                agent.save(out / "checkpoints" / "best.pt", last_eval)

    wall = time.time() - t0
    json.dump({"steps": cfg.steps, "wall_s": round(wall, 1), "dreams": collected * B,
               "best_greedy_sr": best, "best": best_eval, "final": last_eval},
              open(out / "final.json", "w"), indent=1)
    print(f"PMPO-DONE {out.name} best greedy SR {best:.4f} | {wall / 60:.2f} min", flush=True)
    mf.close()
    writer.close()


if __name__ == "__main__":
    main()
