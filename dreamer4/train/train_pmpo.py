"""Phase 3 -- PMPO reinforcement learning for the policy, entirely in imagination.

    Phase 3: Imagination Training -- Optimize policy head using (11) and value head using (10) on
    trajectories generated by the world model and the policy head.        (paper Algorithm 1)

Input: the phase-1 world model (``--dyn``, which names the dataset and the tokenizer) and a
phase-2 checkpoint (``--init_from``), which supplies the finetuned transformer, the agent heads, the
frozen behavioral prior and the frozen reward head. The checkpoints written here carry the same
things, so a run can also be continued from one of its own. No environment is stepped during
training.

One network does everything, as in the paper: the transformer phase 2 finetuned is what the agent
heads READ and what GENERATES the next imagined frame.

The policy, reward and value heads sit on AGENT tokens inside the dynamics transformer
(:mod:`dreamer4.models.agent_heads`). The transformer is FROZEN here -- "We only update the policy
and value heads and keep the transformer frozen" (Section 3.3) -- so a rollout buffers the agent
embeddings ``h_t`` it produced and the update re-runs only the heads over them. The value head is a
symexp two-hot distribution trained by cross-entropy on the lambda-return (Eq. 10); the policy is
trained with PMPO (Eq. 11): the sign of the advantage, ``alpha`` between the positive and negative
sets, and a fixed ``beta`` on the reverse KL to the behavioral prior.

    * a dream ENDS when the reward head says it ended, through the dataset's own terminal rule
      applied to the head's distribution (``terminal_bins``);
    * the reward is the head's, not the task's arithmetic -- nothing here knows what the
      environment pays;
    * dreams start from recorded CONTEXTS (:class:`DemoStarts`) -- "Imagined rollouts start from
      contexts of the dataset that was used during the earlier training phases" -- one rollout per
      context;
    * evaluation is always the REAL environment, every ``--eval_every`` steps, and it is what
      selects ``best.pt``.

Writes to ``--out``: ``config.json``, ``metrics.jsonl``, ``checkpoints/{latest,best}.pt``,
``final.json`` and TensorBoard scalars under ``tb/``. A rerun into the same ``--out`` REPLACES all
of them.

    python -m dreamer4.train.train_pmpo --dyn <phase-1 ckpt> \\
        --init_from runs/heads/checkpoints/best.pt --out runs/rl --K 1 --steps 3200
"""
